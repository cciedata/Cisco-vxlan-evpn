"""site_tables: Markdown tables per site (P2-107): prefix hierarchy, VLAN -> VNI -> VRF, BGP sessions.

Sessions are derived from the data the configs render from: spine route reflectors and their clients (same fabric ASN,
loopback0), attachments (leaf .1/.2 <-> firewall .3 of each /29), ISP router cross-link /31 and carrier /30s.
"""
import ipaddress

from infrahub_sdk.transforms import InfrahubTransform


def v(node, *path):
    for p in path:
        node = (node or {}).get(p)
    return node


def natural(name):
    import re
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", str(name))]


class SiteTables(InfrahubTransform):
    query = "site_tables"

    async def transform(self, data: dict) -> str:
        devs = {}
        for e in data["DcimDevice"]["edges"]:
            d = e["node"]
            addrs = {}
            for ie in d["interfaces"]["edges"]:
                i = ie["node"]
                addrs[i["name"]["value"]] = ([a["node"]["address"]["value"] for a in (v(i, "ip_addresses") or {}).get("edges", [])],
                                             v(i, "role", "value"))
            devs[d["name"]["value"]] = {"role": d["role"]["value"], "asn": v(d, "asn", "node", "asn", "value"), "ifs": addrs}
        site = next(iter(devs)).split("-")[0] if devs else "SITE"
        out = [f"# {site}: addressing, segments and BGP sessions", "",
               "Generated by Infrahub (site_tables transform). Do not edit by hand.", ""]

        # ---- prefix hierarchy
        prefixes = sorted(((ipaddress.ip_network(e["node"]["prefix"]["value"]), e["node"]) for e in data["IpamPrefix"]["edges"]),
                          key=lambda t: (t[0].network_address, t[0].prefixlen))
        out += ["## Prefix hierarchy", "", "| Prefix | Description | Role | Member type |", "|---|---|---|---|"]
        for net, n in prefixes:
            depth = sum(1 for other, _ in prefixes if other != net and net.subnet_of(other))
            out.append(f"| {'&nbsp;&nbsp;' * depth}{net} | {v(n, 'description', 'value') or ''} | {v(n, 'role', 'value') or ''} | {v(n, 'member_type', 'value') or ''} |")

        # ---- VLAN -> VNI -> VRF
        out += ["", "## VLAN -> L2VNI -> VRF (L3VNI)", "", "| VLAN | Segment | L2VNI | Prefix | VRF | L3VNI |", "|---|---|---|---|---|---|"]
        segs = sorted((e["node"] for e in data["FabricSegment"]["edges"]), key=lambda s: v(s, "vlan_id", "value") or 0)
        for s in segs:
            out.append(f"| {v(s, 'vlan_id', 'value')} | {v(s, 'name', 'value')} | {v(s, 'l2_vni', 'value')} | "
                       f"{v(s, 'prefix', 'node', 'prefix', 'value') or ''} | {v(s, 'vrf', 'node', 'name', 'value')} | {v(s, 'vrf', 'node', 'l3_vni', 'value')} |")
        out += ["", "| VRF | L3VNI | L3VNI VLAN |", "|---|---|---|"]
        for e in sorted(data["FabricVRF"]["edges"], key=lambda e: e["node"]["name"]["value"]):
            out.append(f"| {e['node']['name']['value']} | {v(e['node'], 'l3_vni', 'value')} | {v(e['node'], 'l3_vni_vlan', 'value')} |")

        # ---- BGP sessions
        rows = []
        lo0 = {n: (d["ifs"].get("loopback0", ([], None))[0] or [None])[0] for n, d in devs.items()}
        spines = [n for n, d in devs.items() if d["role"] == "spine"]
        for s in spines:
            for n, d in sorted(devs.items(), key=lambda t: natural(t[0])):
                if n != s and d["asn"] and d["asn"] == devs[s]["asn"] and d["role"] != "spine" and lo0.get(n):
                    rows.append(("iBGP L2VPN EVPN", "default", s, lo0[s], devs[s]["asn"], n, lo0[n], d["asn"], "route-reflector client"))
        for e in data["FabricAttachment"]["edges"]:
            a = e["node"]
            net = ipaddress.ip_network(a["prefix"]["node"]["prefix"]["value"])
            members = [m["node"] for m in (v(a, "switch_pair", "node", "members") or {}).get("edges", [])]
            fws = [d["node"] for d in a["devices"]["edges"]]
            fw_asn = v(fws[0], "asn", "node", "asn", "value") if fws else None
            for k, m in enumerate(members):
                rows.append(("eBGP", a["vrf"]["node"]["name"]["value"], m["name"]["value"], f"{net[1 + k]}/{net.prefixlen}",
                             v(m, "asn", "node", "asn", "value"), "/".join(f["name"]["value"] for f in fws), f"{net[3]}/{net.prefixlen}",
                             fw_asn, f"{a['name']['value']} VLAN {a['vlan_id']['value']} (active unit only)"))
        for n, d in sorted(devs.items(), key=lambda t: natural(t[0])):
            if d["role"] != "isp_router":
                continue
            for ifn, (addrs, role) in d["ifs"].items():
                for addr in addrs:
                    iface = ipaddress.ip_interface(addr)
                    if iface.network.prefixlen == 30 and role == "upstream":
                        peer = next(h for h in iface.network.hosts() if h != iface.ip)
                        rows.append(("eBGP", "default", n, addr, d["asn"], "carrier", f"{peer}/30", "", f"{ifn}"))
                    if iface.network.prefixlen == 31 and role == "core":
                        other = [o for o, od in devs.items() if o != n and od["role"] == "isp_router"]
                        peer = next(h for h in (iface.network.network_address, iface.network.broadcast_address) if h != iface.ip)
                        if other and n < other[0]:
                            rows.append(("iBGP", "default", n, addr, d["asn"], other[0], f"{peer}/31", d["asn"], f"cross-link {ifn}"))
        out += ["", "## BGP sessions", "", "| Type | VRF | Local | Local address | Local AS | Peer | Peer address | Peer AS | Note |",
                "|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            out.append("| " + " | ".join("" if x is None else str(x) for x in r) + " |")
        out.append(f"\nTotals: {len(prefixes)} prefixes, {len(segs)} segments, {len(rows)} BGP sessions.")
        return "\n".join(out) + "\n"
